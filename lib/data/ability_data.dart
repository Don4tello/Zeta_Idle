  static List<HeroAbility> unlockedFor(DndClass cls, int heroLevel, {bool ultUnlocked = false}) {
    final list = forClass(cls).where((a) => heroLevel >= a.levelRequired).toList();
    final ult = ultimateFor(cls);
    if (ult != null && ultUnlocked) list.add(ult);
    return list;
  }

