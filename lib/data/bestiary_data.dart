// ── Helpers ────────────────────────────────────────────────────────────────────

BestiaryEntry? bestiaryFor(String enemyId) {
  try {
    return kBestiaryEntries.firstWhere((e) => e.enemyId == enemyId);
  } catch (_) {
    return null;
  }
}

// Scales from 0% (0 kills) to +10% (100 kills), at +1% per 10 kills.
double weaknessBonusMult(String enemyId, int kills) {
  final entry = bestiaryFor(enemyId);
  if (entry == null || kills == 0) return 1.0;
  final pct = (kills ~/ 10).clamp(0, 10);
  return 1.0 + pct / 100.0;
}
